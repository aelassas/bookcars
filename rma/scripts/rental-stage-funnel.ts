/**
 * rental-stage-funnel.ts — emit the SQL that puts Babek's funnel on the RENTAL
 * Twenty instance's opportunity board.
 *
 *   npx tsx scripts/rental-stage-funnel.ts > /tmp/rental-stage-funnel.sql
 *   docker cp /tmp/rental-stage-funnel.sql twenty-rental-db-1:/tmp/f.sql
 *   docker exec twenty-rental-db-1 psql -U postgres -d default -v ON_ERROR_STOP=1 -f /tmp/f.sql
 *   docker exec twenty-rental-server-1 sh -c 'yarn command:prod cache:flush'
 *   docker restart twenty-rental-server-1
 *
 * ── WHY A GENERATOR AND NOT A HAND-WRITTEN .sql ─────────────────────────────
 * Four things have to hold the same list of stages: the Postgres enum, the
 * column's rows, `core."fieldMetadata".options`, and the kanban's viewGroups.
 * Twenty renders "Sorry, something went wrong" the moment the enum and the
 * options disagree, and a row left holding a dropped value cannot be read at
 * all. Hand-maintaining four copies is how that happens; here all four are
 * printed from ONE list — RENTAL_STAGES in src/platform/integrations/twenty/
 * stages.ts, the same list the Bitrix mirror writes through.
 *
 * The output is IDEMPOTENT: the retype is guarded on the enum not already
 * carrying the new values, and the metadata/viewGroup writes are upserts.
 *
 * ⚠ RENTAL ONLY. The sales instance keeps Twenty's stock funnel — Azat's
 * desk is a different business and putting the rent desk's columns on it is
 * exactly the mistake that got our messages filed as spam.
 */
import { createHash } from "node:crypto";
import { RENTAL_STAGES, stageVocabulary } from "@/platform/integrations/twenty/stages";

/** Rental workspace schema (twenty-rental-db-1, workspace of babek@easyrent.com). */
const SCHEMA = "workspace_7tkxm1eeqb4iopvi5ica5vos4";
/** opportunity.stage fieldMetadata row on the rental instance. */
const STAGE_FIELD_ID = "a44d0906-7d2f-4958-8f2a-30e618754122";
/** The "By Stage" KANBAN view — the board Babek actually opens. */
const KANBAN_VIEW_ID = "dfed35c7-e0af-43f1-a5cd-d771f5d14d0a";

const vocab = stageVocabulary("rental");
const FIRST = RENTAL_STAGES[0].value;

/**
 * Stable option/group ids. Twenty needs uuids and re-running must not mint new
 * ones (a changed option id detaches every record's colour and re-creates the
 * kanban column), so they are DERIVED from the stage value rather than random.
 */
function stableUuid(namespace: string, value: string): string {
  const h = createHash("sha1").update(`${namespace}:${value}`).digest("hex");
  // Shape the digest into a syntactically valid v5-looking uuid.
  const v = `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
  return v;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const options = RENTAL_STAGES.map((s, i) => ({
  id: stableUuid("rental-stage-option", s.value),
  color: s.color,
  label: s.label,
  value: s.value,
  position: i,
}));

/**
 * Old value → new value for the 1,099 deals already on the board. This is the
 * SAME table the mirror translates through (stages.ts fromCanonical), inverted
 * — so a deal migrated here and a deal re-synced tomorrow land in the same
 * column by construction. Anything unexpected falls to the first stage rather
 * than being left holding a value that no longer exists.
 */
const ROW_MIGRATION = Object.entries(vocab.fromCanonical);

const lines: string[] = [];
const p = (s = "") => lines.push(s);

p(`-- GENERATED by scripts/rental-stage-funnel.ts — do not edit by hand.`);
p(`-- Rental Twenty instance (:3002) only. Idempotent.`);
p(`\\set ON_ERROR_STOP on`);
p(`BEGIN;`);
p();
p(`-- 1. Retype opportunity.stage onto Babek's funnel.`);
p(`--    A Postgres enum value cannot be dropped, so the type is rebuilt and`);
p(`--    the rows are cast through the mapping in the same statement — there is`);
p(`--    no window in which a row holds a value the type does not have.`);
p(`DO $$`);
p(`BEGIN`);
p(`  IF NOT EXISTS (`);
p(`    SELECT 1 FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid`);
p(`     WHERE t.typname = 'opportunity_stage_enum'`);
p(`       AND t.typnamespace = ${q(SCHEMA)}::regnamespace`);
p(`       AND e.enumlabel = ${q(FIRST)}`);
p(`  ) THEN`);
p(`    CREATE TYPE "${SCHEMA}"."opportunity_stage_enum_next" AS ENUM (`);
p(`      ${RENTAL_STAGES.map((s) => q(s.value)).join(", ")}`);
p(`    );`);
p(`    ALTER TABLE "${SCHEMA}"."opportunity" ALTER COLUMN "stage" DROP DEFAULT;`);
p(`    ALTER TABLE "${SCHEMA}"."opportunity"`);
p(`      ALTER COLUMN "stage" TYPE "${SCHEMA}"."opportunity_stage_enum_next"`);
p(`      USING (CASE "stage"::text`);
for (const [from, to] of ROW_MIGRATION) p(`        WHEN ${q(from)} THEN ${q(to)}`);
p(`        ELSE ${q(FIRST)}`);
p(`      END)::"${SCHEMA}"."opportunity_stage_enum_next";`);
p(`    DROP TYPE "${SCHEMA}"."opportunity_stage_enum";`);
p(`    ALTER TYPE "${SCHEMA}"."opportunity_stage_enum_next" RENAME TO "opportunity_stage_enum";`);
p(`    ALTER TABLE "${SCHEMA}"."opportunity"`);
p(`      ALTER COLUMN "stage" SET DEFAULT ${q(FIRST)}::"${SCHEMA}"."opportunity_stage_enum";`);
p(`  END IF;`);
p(`END $$;`);
p();
p(`-- 2. Field metadata must match the enum EXACTLY or every board render fails.`);
p(`UPDATE core."fieldMetadata"`);
p(`   SET options = ${q(JSON.stringify(options))}::jsonb,`);
p(`       "defaultValue" = ${q(JSON.stringify(`'${FIRST}'`))}::jsonb,`);
p(`       "updatedAt" = now()`);
p(` WHERE id = ${q(STAGE_FIELD_ID)};`);
p();
p(`-- 3. Kanban columns. Upserted on a derived id, so a re-run moves/renames`);
p(`--    the existing column instead of minting a second one.`);
p(`INSERT INTO core."viewGroup"`);
p(`  (id, "universalIdentifier", "fieldValue", position, "isVisible", "viewId", "workspaceId", "applicationId", "createdAt", "updatedAt")`);
p(`SELECT g.id, g.id, g."fieldValue", g.position, true, v.id, v."workspaceId", v."applicationId", now(), now()`);
p(`  FROM (VALUES`);
p(
  options
    .map((o) => `    (${q(stableUuid("rental-stage-group", o.value))}::uuid, ${q(o.value)}, ${o.position}::double precision)`)
    .join(",\n")
);
p(`  ) AS g(id, "fieldValue", position)`);
p(`  CROSS JOIN (`);
p(`    SELECT ${q(KANBAN_VIEW_ID)}::uuid AS id,`);
p(`           (SELECT "workspaceId" FROM core.view WHERE id = ${q(KANBAN_VIEW_ID)}) AS "workspaceId",`);
p(`           -- applicationId is NOT NULL and Twenty owns the value; it is`);
p(`           -- borrowed from a group already on this view, else from the view.`);
p(`           COALESCE(`);
p(`             (SELECT "applicationId" FROM core."viewGroup" WHERE "viewId" = ${q(KANBAN_VIEW_ID)} LIMIT 1),`);
p(`             (SELECT "applicationId" FROM core.view WHERE id = ${q(KANBAN_VIEW_ID)})`);
p(`           ) AS "applicationId"`);
p(`  ) AS v`);
p(`ON CONFLICT (id) DO UPDATE`);
p(`   SET "fieldValue" = EXCLUDED."fieldValue",`);
p(`       position = EXCLUDED.position,`);
p(`       "isVisible" = true,`);
p(`       "deletedAt" = NULL,`);
p(`       "updatedAt" = now();`);
p();
p(`-- 4. Retire the stock columns (NEW/SCREENING/...) left on this view.`);
p(`DELETE FROM core."viewGroup"`);
p(` WHERE "viewId" = ${q(KANBAN_VIEW_ID)}`);
p(`   AND "fieldValue" NOT IN (${RENTAL_STAGES.map((s) => q(s.value)).join(", ")});`);
p();
p(`-- 5. The board's own filter. It hid ["LOST","CUSTOMER"] — values that no`);
p(`--    longer exist, which would stop matching and refill the board with dead`);
p(`--    deals. Only the cancelled ones are hidden now: "successful deal" is a`);
p(`--    column Babek asked for by name, so it stays on the board.`);
p(`--    A SELECT filter is ONE row whose value is a JSON ARRAY.`);
p(`UPDATE core."viewFilter"`);
p(`   SET value = ${q(JSON.stringify([vocab.lost]))}::jsonb, "updatedAt" = now()`);
p(` WHERE "viewId" = ${q(KANBAN_VIEW_ID)}`);
p(`   AND "fieldMetadataId" = ${q(STAGE_FIELD_ID)};`);
p();
p(`COMMIT;`);
p();
p(`-- Post-conditions (must print zero rows / matching lists).`);
p(`SELECT stage, count(*) FROM "${SCHEMA}"."opportunity" WHERE "deletedAt" IS NULL GROUP BY 1 ORDER BY 1;`);
p(`SELECT unnest(enum_range(NULL::"${SCHEMA}"."opportunity_stage_enum")) AS enum_value;`);
p(`SELECT jsonb_array_elements(options)->>'value' AS option_value FROM core."fieldMetadata" WHERE id = ${q(STAGE_FIELD_ID)};`);
p(`SELECT "fieldValue", position, "isVisible" FROM core."viewGroup" WHERE "viewId" = ${q(KANBAN_VIEW_ID)} ORDER BY position;`);

process.stdout.write(lines.join("\n") + "\n");
